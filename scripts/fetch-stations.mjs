/**
 * Collects the Metro and Cercanías (suburban train) stations in the city of
 * Madrid from OpenStreetMap and writes lib/stations-data.ts, which the trip
 * time estimates use.
 *
 *   npm run stations
 *
 * Run by hand, like the shops: Overpass is slow and rate limited.
 */

import { writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const QUERY = `[out:json][timeout:120];
area["name"="Madrid"]["boundary"="administrative"]["admin_level"="8"]->.madrid;
nwr(area.madrid)["railway"="station"];
out center tags;`;

const MIRRORS = [
  "https://overpass-api.de/api/interpreter",
  "https://overpass.kumi.systems/api/interpreter",
  "https://overpass.private.coffee/api/interpreter",
];

async function ask() {
  let last = "none tried";
  for (const mirror of MIRRORS) {
    try {
      const response = await fetch(mirror, {
        method: "POST",
        headers: {
          "Content-Type": "application/x-www-form-urlencoded",
          Accept: "application/json",
          "User-Agent": "Cheap Groceries-student-project/0.1",
        },
        body: new URLSearchParams({ data: QUERY }),
      });
      if (response.ok) return response.json();
      last = `HTTP ${response.status}`;
    } catch (error) {
      last = error.message;
    }
    console.warn(`  ! ${new URL(mirror).host}: ${last}`);
  }
  throw new Error(`every Overpass mirror failed (${last})`);
}

const round = (value) => Math.round(value * 1e5) / 1e5;

const payload = await ask();
console.log(`  ${payload.elements?.length ?? 0} station elements${payload.remark ? ` (${payload.remark})` : ""}`);
const metro = new Map();
const train = new Map();
for (const element of payload.elements ?? []) {
  const tags = element.tags ?? {};
  const name = tags.name;
  const lat = element.lat ?? element.center?.lat;
  const lon = element.lon ?? element.center?.lon;
  if (!name || typeof lat !== "number" || typeof lon !== "number") continue;
  const point = { name, lat: round(lat), lon: round(lon) };
  const network = `${tags.network ?? ""} ${tags.operator ?? ""}`;
  // Metro and Metro Ligero (light rail) run like the Metro; Cercanías is the train.
  const isMetro = ["subway", "light_rail"].includes(tags.station) || /metro/i.test(network);
  const isTrain = tags.train === "yes" || /cercan|renfe/i.test(network);
  // One entry per station name and kind: big stations are mapped several times.
  if (isMetro && !metro.has(name)) metro.set(name, point);
  if (isTrain && !train.has(name)) train.set(name, point);
}

const data = {
  collected_on: new Date().toISOString().slice(0, 10),
  source: "OpenStreetMap via Overpass API, © OpenStreetMap contributors (ODbL)",
  metro: [...metro.values()].sort((a, b) => a.name.localeCompare(b.name)),
  train: [...train.values()].sort((a, b) => a.name.localeCompare(b.name)),
};

await writeFile(
  resolve(ROOT, "lib/stations-data.ts"),
  `// Generated by scripts/fetch-stations.mjs — run \`npm run stations\` to refresh.\n` +
    `// Source: OpenStreetMap via Overpass API, © OpenStreetMap contributors (ODbL).\n\n` +
    `const stationData = ${JSON.stringify(data)};\n\nexport default stationData;\n`,
  "utf8",
);
console.log(`${data.metro.length} Metro stations, ${data.train.length} Cercanías stations -> lib/stations-data.ts`);
